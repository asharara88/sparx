// Turn transcribed shop orders (data/orders.json, gitignored) into one compact, idempotent SQL
// script: receipts + lines + list items + aliases + purchases, then the learned reorder interval.
// Dated orders are applied; undated ones are left "read" so the date is set in the app, then applied.
//   node scripts/backfill/receipts-sql.mjs > data/sql/receipts-backfill.sql
import { readFileSync } from "node:fs";
const orders = JSON.parse(readFileSync(new URL("../../data/orders.json", import.meta.url), "utf8"));
const MIDO = "00000000-0000-4000-8000-000000000001";
const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const n = (x) => (x === null || x === undefined ? "null" : String(x));
const rRows = orders.map((o) => `(${q(o.key)},${q(o.store_id ?? "talabat")},${q(o.store)},${q(o.date)},${n(o.total)},${q(o.note ?? "From an order screenshot (backfill).")})`);
const lRows = orders.flatMap((o) => o.lines.map(([text, qty, total, cat], i) => `(${q(o.key)},${i + 1},${q(text)},${qty},${total},${q(cat)})`));
// an item for a printed line: by name, then by remembered alias
const ITEM = (t) => `coalesce((select i.id from public.shopping_items i where i.deleted_at is null and lower(i.name) = lower(${t}) limit 1),
      (select a.item_id from public.shopping_item_aliases a where lower(a.alias) = lower(${t}) limit 1))`;
console.log(`-- receipts backfill (generated by scripts/backfill/receipts-sql.mjs); safe to run twice
create temp table bf_r (key text, store_id text, store_name text, bought_on date, total numeric, note text);
insert into bf_r values
${rRows.join(",\n")};
create temp table bf_l (key text, n int, txt text, qty numeric, total numeric, cat text);
insert into bf_l values
${lRows.join(",\n")};

-- 1. list items: one per distinct printed name, unless the name or an alias is already known
insert into public.shopping_items (id, name, category, store_id, needed, created_by)
select distinct on (lower(l.txt)) md5('receipts-backfill|item|' || lower(l.txt))::uuid, l.txt, l.cat, r.store_id, false, '${MIDO}'
  from bf_l l join bf_r r on r.key = l.key
 where l.cat <> 'skip'
   and not exists (select 1 from public.shopping_items i where i.deleted_at is null and lower(i.name) = lower(l.txt))
   and not exists (select 1 from public.shopping_item_aliases a where lower(a.alias) = lower(l.txt))
 order by lower(l.txt), l.key
on conflict (id) do nothing;

-- 2. receipts (dated ones applied, undated ones waiting for a date)
insert into public.receipts (id, store_id, store_name, bought_on, total, currency, photo_path, extracted, status, note, created_by, applied_at)
select md5('receipts-backfill|receipt|' || r.key)::uuid, r.store_id, r.store_name, r.bought_on, r.total, 'AED', 'receipts/backfill/' || r.key || '.png',
       (select jsonb_build_object('store', r.store_name, 'date', r.bought_on, 'currency', 'AED', 'total', r.total,
               'lines', jsonb_agg(jsonb_build_object('text', l.txt, 'qty', l.qty, 'unit_price', round(l.total / l.qty, 2), 'line_total', l.total, 'item_id', null) order by l.n))
          from bf_l l where l.key = r.key),
       case when r.bought_on is null then 'read' else 'applied' end, r.note, '${MIDO}', case when r.bought_on is null then null else now() end
  from bf_r r
on conflict (id) do nothing;

-- 3. lines, matched to the items
insert into public.receipt_lines (id, receipt_id, line_no, text, qty, unit_price, line_total, item_id, match, confidence)
select md5('receipts-backfill|line|' || l.key || '|' || l.n)::uuid, md5('receipts-backfill|receipt|' || l.key)::uuid, l.n, l.txt, l.qty, round(l.total / l.qty, 2), l.total,
       case when l.cat = 'skip' then null else ${ITEM("l.txt")} end,
       case when l.cat = 'skip' then 'skipped' else 'confirmed' end, case when l.cat = 'skip' then null else 1.0 end
  from bf_l l
on conflict (receipt_id, line_no) do nothing;

-- 4. the printed names become aliases
insert into public.shopping_item_aliases (item_id, alias)
select x.item_id, x.txt from (select ${ITEM("l.txt")} as item_id, l.txt from bf_l l where l.cat <> 'skip') x where x.item_id is not null
on conflict do nothing;

-- 5. purchases for the dated receipts
insert into public.purchases (id, item_id, receipt_id, line_id, bought_on, store_id, qty, price)
select md5('receipts-backfill|purchase|' || l.key || '|' || l.n)::uuid, x.item_id, md5('receipts-backfill|receipt|' || l.key)::uuid,
       md5('receipts-backfill|line|' || l.key || '|' || l.n)::uuid, r.bought_on, r.store_id, l.qty, round(l.total / l.qty, 2)
  from bf_l l join bf_r r on r.key = l.key
  cross join lateral (select ${ITEM("l.txt")} as item_id) x
 where l.cat <> 'skip' and r.bought_on is not null and x.item_id is not null
on conflict (id) do nothing;

-- 6. last bought / last price, then the learned interval
update public.shopping_items i set last_bought_on = p.d, last_price = p.price, last_price_store = p.store_id
  from (select distinct on (item_id) item_id, bought_on as d, price, store_id from public.purchases order by item_id, bought_on desc, created_at desc) p
 where p.item_id = i.id and (i.last_bought_on is null or i.last_bought_on <= p.d);
select count(*) as learned from (select private.learn_reorder(item_id) from (select distinct item_id from public.purchases) x) y;`);
